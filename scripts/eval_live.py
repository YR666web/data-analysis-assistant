def make_attachment(path):
    import pandas as pd
    rows = []
    for week in range(5):
        for i in range(8):
            rows.append({"日期": f"2025-09-{1+week*6+i%5:02}", "分类": "抗生素" if i % 2 == 0 else "非抗生素",
                         "销售额": str(Decimal(week + 1) * Decimal(i + 1) / 10)})
    # A large out-of-period value catches unfiltered full-table aggregates.
    rows.append({"日期": "2025-10-01", "分类": "非抗生素", "销售额": "9999"})
    with pd.ExcelWriter(path) as writer:
        pd.DataFrame(rows).to_excel(writer, sheet_name="销售明细", index=False)
        pd.DataFrame({"说明": ["仅供说明，不参与统计"]}).to_excel(writer, sheet_name="说明", index=False)


def grade(report, expected):
    """Strict final-answer match; arbitrary numbers elsewhere cannot earn credit."""
    matches = re.findall(r'EVAL_RESULT\s*(\{[^{}]*\})', report)
    if len(matches) != 1:
        return False, "missing_or_multiple_final_result"
    try:
        value = json.loads(matches[0])["value"]
        if value is None or expected is None:
            return value is None and expected is None, "null_comparison"
        actual, truth = Decimal(str(value)), Decimal(str(expected))
        return actual.is_finite() and truth.is_finite() and actual == truth, "numeric_exact_match"
    except (ValueError, KeyError, TypeError, InvalidOperation):
        return False, "invalid_numeric_result"


def metrics(events):
    validations = [e["data"] for e in events if e["event"] == "validation_result"]
    results = [e["data"] for e in events if e["event"] == "tool_result"]
    usages = [e["data"].get("usage") for e in events if e["event"] == "model_usage"]
    timeouts = sum(e["event"] == "review_timeout" for e in events)
    reviews = [e["data"]["status"] for e in events if e["event"] == "review_result"]
    first = validations[0] if validations else None
    first_pass = bool(first and first["accepted"] and (not first["review_requested"] or (reviews and reviews[0] == "passed")))
    if timeouts:
        first_pass = False  # Conservatively never call a skipped review a pass.
    complete_usage = bool(usages) and all(u is not None for u in usages)
    return {"first_round_validator_pass": first_pass,
            "final_validator_pass": bool(validations and validations[-1]["accepted"] and not timeouts),
            "rounds": len(validations), "review_timeouts": timeouts,
            "delegations": sum(e["event"] == "assistant_call" for e in events),
            "tool_calls": len(results), "tool_failures": sum(not r.get("success", False) for r in results),
            "model_calls_with_usage_event": len(usages), "usage_complete": complete_usage,
            "tokens": sum(u.get("total_tokens", 0) for u in usages) if complete_usage else None,
            "observed_tokens": sum(u.get("total_tokens", 0) for u in usages if u)}


def summarize(records, planned):
    groups = {}
    for mode in ("multi", "single"):
        rs = [r for r in records if r["mode"] == mode]
        if not rs:
            continue
        completed = [r for r in rs if r["status"] == "completed"]
        calls = sum(r["metrics"]["tool_calls"] for r in rs)
        times = sorted(r["seconds"] for r in rs)
        groups[mode] = {"planned": planned, "attempted": len(rs), "completed": len(completed),
            "numeric_correct": sum(r["numeric_correct"] for r in rs),
            "numeric_accuracy_all_attempts": sum(r["numeric_correct"] for r in rs) / len(rs),
            "first_round_validator_pass_rate": sum(r["metrics"]["first_round_validator_pass"] for r in rs) / len(rs),
            "final_validator_pass_rate": sum(r["metrics"]["final_validator_pass"] for r in rs) / len(rs),
            "mean_seconds_all_attempts": statistics.mean(times),
            "p95_seconds_all_attempts": times[max(0, __import__('math').ceil(.95 * len(times)) - 1)],
            "mean_delegations": statistics.mean(r["metrics"]["delegations"] for r in rs),
            "tool_failure_rate": sum(r["metrics"]["tool_failures"] for r in rs) / calls if calls else None,
            "mean_tokens": statistics.mean(r["metrics"]["tokens"] for r in rs) if all(r["metrics"]["tokens"] is not None for r in rs) else None,
            "human_reviewed_success_rate": None,
            "by_source": {src: {"attempted": len([r for r in rs if r["source"] == src]),
                                  "correct": sum(r["numeric_correct"] for r in rs if r["source"] == src)}
                          for src in ("database", "attachment")}}
    return groups


async def run(args, directory, dataset):
    from agent import main_agent as ma
    from api import context
    from api.monitor import monitor, manager
    from deepagents import create_deep_agent
    from langchain.agents.middleware.types import AgentMiddleware
    from tools.mysql_tools import _get_connection
    from utils import path_utils

    # A no-op replaces only delegation middleware by its documented name slot.
    # Remaining DeepAgents middleware stays the same in both arms.
    class NoDelegation(AgentMiddleware):
        @property
        def name(self):
            return "SubAgentMiddleware"

    original_model = ma.get_llm
    original_report = monitor.report

    def model():
        llm = original_model()
        llm.temperature = 0
        llm.max_tokens = 1500
        llm.request_timeout = 30
        llm.max_retries = 0
        llm.stream_usage = True
        return llm

    def factory():
        mode = ACTIVE.get()["mode"]
        if mode == "multi":
            return create_deep_agent(model=model(), tools=ma._FILE_TOOLS,
                                     system_prompt=ma.main_agent_config["system_prompt"], subagents=ma.SUBAGENTS)
        all_tools = list(ma._FILE_TOOLS)
        for sub in ma.SUBAGENTS:
            all_tools.extend(sub["tools"])
        # Retain domain instructions, replace only role/delegation statements.
        prompt = ma.main_agent_config["system_prompt"].split("先识别用户要的交付物：", 1)[1]
        prompt = "你直接使用全部业务工具完成分析，不委派子 Agent。先识别用户要的交付物：" + prompt
        prompt += "\n各数据源操作说明：\n" + "\n".join(s["system_prompt"] for s in ma.SUBAGENTS)
        return create_deep_agent(model=model(), tools=all_tools, system_prompt=prompt,
                                 subagents=[], middleware=[NoDelegation()])

    async def capture(thread_id, event, message, data=None):
        current = ACTIVE.get()
        if current is not None and event not in {"model_delta", "model_start", "model_end"}:
            current["events"].append({"event": event, "data": data or {}, "elapsed": time.perf_counter() - current["start"]})
        await original_report(thread_id, event, message, data)

    # Freeze independently queried answers before either architecture sees cases.
    connection = _get_connection()
    cursor = connection.cursor()
    for case in dataset:
        if case["source"] == "database":
            cursor.execute(case["oracle_sql"])
            value = cursor.fetchone()[0]
            case["expected"] = None if value is None else str(value)
    connection.close()
    (directory / "cases.json").write_text(json.dumps(dataset, ensure_ascii=False, indent=2), encoding="utf-8")
    records = []
    semaphore = asyncio.Semaphore(args.concurrency)

    async def one(case, mode):
        async with semaphore:
            thread_id = f"eval_{directory.name}_{case['id']}_{mode}"
            upload = path_utils.get_upload_dir(thread_id)
            if case["source"] == "attachment":
                upload.mkdir(parents=True, exist_ok=True)
                make_attachment(upload / "benchmark.xlsx")
            started = time.perf_counter()
            current = {"mode": mode, "events": [], "start": started}
            token = ACTIVE.set(current)
            report, error, status = "", None, "completed"
            query = case["question"] + (
                "。生成简短 Markdown 分析报告，注明来源、筛选范围和所求结果。"
                '报告正文末尾必须且仅出现一次 EVAL_RESULT {"value":"所求数值"}，'
                'value 使用不带千分位或单位的十进制字符串；无可计算结果用 null。'
                "不要查询无关来源，不需要 PDF。")
            try:
                report = await asyncio.wait_for(ma.run_deep_agent(query, thread_id), args.timeout)
            except Exception as exc:
                status, error = "failed", type(exc).__name__
            finally:
                context.reset_session()
                ACTIVE.reset(token)
                manager.clear_streams(thread_id)
            correct, reason = grade(report, case["expected"])
            record = {"id": case["id"], "mode": mode, "source": case["source"], "status": status,
                      "error": error, "seconds": round(time.perf_counter() - started, 3),
                      "numeric_correct": status == "completed" and correct, "grading_reason": reason,
                      "expected": case["expected"], "report": report, "human_review": None,
                      "metrics": metrics(current["events"]), "events": current["events"]}
            (directory / f"{case['id']}_{mode}.json").write_text(json.dumps(record, ensure_ascii=False, indent=2), encoding="utf-8")
            records.append(record)
            (directory / "summary.json").write_text(json.dumps(summarize(records, len(dataset)), ensure_ascii=False, indent=2), encoding="utf-8")
            print(json.dumps({"done": len(records), "total": 2 * len(dataset), "id": case["id"], "mode": mode,
                              "status": status, "correct": record["numeric_correct"], "seconds": record["seconds"]}), flush=True)

    with patch.object(ma, "create_deep_agent", side_effect=factory), patch.object(ma, "get_llm", side_effect=model), patch.object(monitor, "report", side_effect=capture):
        # AB/BA order alternates; both arms for a question are never concurrent.
        async def pair(index, case):
            for mode in (("multi", "single") if index % 2 == 0 else ("single", "multi")):
                await one(case, mode)
        await asyncio.gather(*(pair(i, c) for i, c in enumerate(dataset)))

    drift = []
    connection = _get_connection()
    cursor = connection.cursor()
    for case in dataset:
        if case["source"] == "database":
            cursor.execute(case["oracle_sql"])
            value = cursor.fetchone()[0]
            if (None if value is None else str(value)) != case["expected"]:
                drift.append(case["id"])
    connection.close()
    (directory / "integrity.json").write_text(json.dumps({"database_changed_cases": drift, "comparison_valid": not drift}), encoding="utf-8")
    with (directory / "human_review.csv").open("w", encoding="utf-8-sig", newline="") as f:
        writer = csv.writer(f)
        writer.writerow(["case_id", "mode", "numeric_correct", "factual_correct", "complete", "source_supported", "reviewer", "notes"])
        for r in sorted(records, key=lambda r: (r["id"], r["mode"])):
            writer.writerow([r["id"], r["mode"], r["numeric_correct"], "", "", "", "", ""])


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--run", action="store_true")
    p.add_argument("--limit", type=int, default=50)
    p.add_argument("--source", choices=["all", "database", "attachment"], default="all")
    p.add_argument("--concurrency", type=int, default=2)
    p.add_argument("--timeout", type=float, default=150)
    args = p.parse_args()
    if not 1 <= args.limit <= 50 or not 1 <= args.concurrency <= 4 or args.timeout <= 0:
        p.error("limit: 1..50; concurrency: 1..4; timeout > 0")
    directory = ROOT / "eval" / "results" / ("live_" + datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%S%f"))
    directory.mkdir(parents=True)
    dataset = [c for c in cases() if args.source == "all" or c["source"] == args.source][:args.limit]
    (directory / "cases.json").write_text(json.dumps(dataset, ensure_ascii=False, indent=2), encoding="utf-8")
    metadata = {"scope": "Real-model numeric reports: live demo MySQL + synthetic attachments; no RAG, internet, PDF or production traffic evaluation.",
                "grading": "Exact numeric final-answer match, not human end-to-end report correctness. Validator acceptance is not factual accuracy.",
                "comparison": "Same DeepAgents defaults except single arm replaces SubAgentMiddleware and receives the union of business tools/domain prompts. Multi retains default general-purpose subagent as in production.",
                "temperature": 0, "max_output_tokens_per_call": 1500, "concurrency": args.concurrency, "timeout_seconds": args.timeout,
                "model": os.getenv("DEEPSEEK_MODEL", "deepseek-chat"), "dataset_cases": len(dataset),
                "packages": {n: importlib.metadata.version(n) for n in ["deepagents", "langchain", "langchain-openai"]},
                "source_sha256": {str(f.relative_to(ROOT)): hashlib.sha256(f.read_bytes()).hexdigest() for f in [Path(__file__), ROOT / "agent/main_agent.py", ROOT / "prompt/prompts.yaml", ROOT / "tools/table_tools.py", ROOT / "tools/reflect_check.py"]}}
    (directory / "metadata.json").write_text(json.dumps(metadata, ensure_ascii=False, indent=2), encoding="utf-8")
    print(str(directory), flush=True)
    if args.run:
        asyncio.run(run(args, directory, dataset))


if __name__ == "__main__":
    main()
